public class DaireHesap {
    public static void main(String[] args) {
        double yaricap = 3.5;
        double pi = Math.PI;
        
        double cevre = 2 * pi * yaricap;
        double alan = pi * yaricap * yaricap;
        
        System.out.println("Cevre: " + cevre);
        System.out.println("Alan: " + alan);
    }
}
